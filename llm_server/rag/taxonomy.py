def classify(title: str, author: str = "") -> dict[str, list[str]]:
    """给一部典籍打四维多标签。

    书名规则与作者规则是**并集**：作者是「郑钦安」会追加火神派，
    书名里的「伤寒」同时命中伤寒派，两者不冲突。

    `内容体裁` 先算，因为另外两个维度要用它兜底：方书/医案本身不分科
    （→ 全科综合），本草查药、方书查方也正是体裁层面的功能（→ 本草集解
    / 方剂汇编）。
    """

"""中医典籍多标签分类（语料整理）。

语料目录里是 694 部中医典籍的纯文本，文件名形如 ``013-本草纲目.txt``。
纯字面检索在这几个需求上会被卡住：

- 「只看儿科书」——检索端没法把《幼科铁镜》《证治准绳·幼科》《婴童百问》
  一次性圈出来，它们的正文里未必出现「儿科」二字；
- 「只看医案」——《临证指南医案》和《洄溪医案》在字面上毫无共同点；
- 「只看火神派」——流派是**人**（郑钦安、吴佩衡）与**主张**的传承，
  郑钦安的《医理真传》通篇不会自称「火神派」。

故做**基于文件（书名 + 头部元数据）的多标签分类**，四个维度正交打标：

=================  ============================================  ==========================
维度               说明                                          例
=================  ============================================  ==========================
``临床学科``       相当于现代医院的科室                          儿科 / 产科 / 骨伤科 / 眼科
``内容体裁``       这本书是「什么类型的著作」                    本草药物 / 方书方剂 / 临证医案
``功能用途``       这本书「拿来干什么」                          炮制制剂 / 歌诀便诵 / 急救方书
``学术流派``       师承与主张                                    伤寒派 / 温热派 / 火神派
=================  ============================================  ==========================

``功能用途`` 是 ``内容体裁`` 的细分：《本草纲目》和《雷公炮炙论》体裁上都是
「本草药物」，但用处完全不同——一个查药性，一个查炮制；方书同理，《普济方》
是查方、《汤头歌诀》是背方、《肘后备急方》是救急。

一本书在每个维度上可以有**多个**标签（《证治准绳·幼科》= 儿科；《妇人大全良方》
= 妇科 + 产科），也可以一个维度都打不上（落 ``未归类``），绝不硬塞标签。

为什么用规则而不是让模型读全文：

- **书名是作者原题**，信息密度极高——「幼科」「疡医」「胎产」「伤寒」这些字眼
  本身就是分类信号，规则命中率高、可解释、可审计；
- **流派可由作者直接判定**（郑钦安 → 火神派，叶天士 → 温热派），
  而正文关键词极不稳定（《医理真传》里「附子」很多，但《伤寒论》里也有）；
- 纯标准库、离线可跑、结果可复现；分类结果落在 JSON 里，人工改标后重跑即生效。

产物有三处：

1. ``classification.json``：全量机器可读结果（含作者/朝代/字数）；
2. ``classification.md``：按标签分组的人读报告；
3. 语料库 ``doc_tags`` 表：检索时可按标签过滤（``search(..., tags=["儿科"])``）。
"""


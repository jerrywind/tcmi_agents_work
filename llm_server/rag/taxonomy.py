def infer_era(dynasty: str) -> str:
    """把「朝代」字段归到时代桶；识别不出返回空串（不强猜）。"""
    d = _norm(dynasty)
    if not d:
        return ""
    for era, keys in _ERA_RULES:
        if any(k in d for k in keys):
            return era
    return ""


@dataclass(frozen=True)
class Rule:
    """一条打标规则。

    ``any_of`` 命中任一即打标，``none_of`` 命中任一则不打标（用来挡住
    「痰火点雪」「痰疠法门」这类字面上撞车、实则分属不同科的例外），
    ``also_of`` 是**必须同时命中**的条件——「专科方书」要求书名既带专科词
    又带「方」字，《外科正宗》只有前者，不能算方书。
    """

    tag: str
    any_of: tuple[str, ...]
    none_of: tuple[str, ...] = ()
    #: 必须**同时**命中任一才打标
    also_of: tuple[str, ...] = ()
    #: 匹配范围：``title``（书名）/ ``author``（作者）/ ``any``（两者）
    field: str = "title"

    def matches(self, title: str, author: str) -> bool:
        hay = {"title": title, "author": author}.get(self.field, f"{title} {author}")
        if self.none_of and any(w in hay for w in self.none_of):
            return False
        if not any(w in hay for w in self.any_of):
            return False
        return not self.also_of or any(w in hay for w in self.also_of)



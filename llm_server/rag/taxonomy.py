# 头部元数据块只有部分典籍有（`<篇名>x / 书名：/ 作者：/ 朝代：/ 年份：`），
# 另有一批是「中医瑰宝苑」导出格式，没有元数据，只能靠书名判断。
_RE_TITLE = re.compile(r"书\s*名\s*[：:]\s*(.+)")
_RE_AUTHOR = re.compile(r"作\s*者\s*[：:]\s*(.+)")
_RE_DYNASTY = re.compile(r"朝\s*代\s*[：:]\s*(.+)")
_RE_YEAR = re.compile(r"年\s*份\s*[：:]\s*(.+)")
# 「原著 清·郑钦安」「原著：吴佩衡」这类非标准写法
_RE_AUTHOR_LOOSE = re.compile(
    r"原\s*著\s*[：:]?\s*(?:[一-鿿]{1,4}\s*[·．.]\s*)?([一-鿿]{2,4})"
)

_ENCODINGS = ("utf-8-sig", "gb18030", "big5hkscs", "utf-16")
#: 只读头部这么多字节即可拿到元数据块，没必要为分类读 161MB 全文
_HEAD_BYTES = 8192


def _norm(s: str) -> str:
    """繁转简 + 去空白，用于规则匹配。"""
    return re.sub(r"\s+", "", (s or "").translate(_TRAD_TO_SIMP))


def read_head(path: Path, limit: int = _HEAD_BYTES) -> str:
    """只读文件头部若干字节并解码。

    截断处可能正好切在多字节汉字中间，故解码失败时退 1~3 字节重试，
    而不是直接 ``errors="ignore"`` 吞掉（那会静默破坏元数据里的作者名）。
    """
    with open(path, "rb") as f:
        raw = f.read(limit)
    for enc in _ENCODINGS:
        for cut in (0, 1, 2, 3):
            try:
                return (raw[: len(raw) - cut] if cut else raw).decode(enc)
            except (UnicodeDecodeError, LookupError):
                continue
    return raw.decode("utf-8", errors="ignore")


def _clean_author(raw: str) -> str:
    """清洗作者字段。

    语料里两种脏数据很常见：一是元数据块串位，作者字段变成「朝代：西汉」；
    二是作者后面跟着句读（「朱震亨、」「罗美。」）。前者直接丢弃，
    后者只削掉标点——作者名后面的顿号常常跟的是合著者，不该整段丢掉。
    """
    s = (raw or "").strip().strip("。、，,；;：: ")
    if not s or s.startswith("朝代") or "：" in s or ":" in s:
        return ""
    return s


def parse_meta(head: str) -> dict[str, str]:
    """从头部元数据块里抽 书名/作者/朝代/年份。"""
    out: dict[str, str] = {}
    for key, rx in (("title", _RE_TITLE), ("author", _RE_AUTHOR),
                    ("dynasty", _RE_DYNASTY), ("year", _RE_YEAR)):
        m = rx.search(head)
        if m:
            out[key] = m.group(1).strip()
    author = _clean_author(out.get("author", ""))
    if not author:
        m = _RE_AUTHOR_LOOSE.search(head)
        if m:
            author = _clean_author(m.group(1))
    if author:
        out["author"] = author
    else:
        out.pop("author", None)
    return out


